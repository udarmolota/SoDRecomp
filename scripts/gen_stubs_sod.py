"""Generates SoDRecomp/SoDRecomp/kernel/import_stubs.cpp: a weak definition for every
__imp__ import SoD's recompiled code references (ppc/ppc_recomp_shared.h). Real
implementations elsewhere (SOD_IMPORT_AS) override these. Based on DAORecomp's
scripts/gen_stubs.py; the difference is the imports Dragon Age: Origins never used.

- Imports DAO also had (its import_stubs.cpp, read-only): SOD_WEAK_STUB, as DAO's
  (logs "Unimplemented import" a few times, returns 0).
- Imports DAO never had (State of Decay's new ones): SOD_UNIMPLEMENTED, which logs the
  same way and returns a failure the caller understands, by family (FAILURES below);
  real implementations come later.

usage: gen_stubs_sod.py
"""
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / 'ppc' / 'ppc_recomp_shared.h'
OUT = ROOT / 'SoDRecomp' / 'SoDRecomp' / 'kernel' / 'import_stubs.cpp'
# XDROID360_ROOT: an XDroid360 checkout (default: the author's layout, one level above this one's
# parent); DAORecomp is its recomp submodule.
XDROID360_ROOT = Path(os.environ.get('XDROID360_ROOT', ROOT.parent.parent / 'DAO'))
DAO_STUBS = XDROID360_ROOT / 'recomp' / 'DAORecomp' / 'kernel' / 'import_stubs.cpp'

STATUS_NOT_IMPLEMENTED = '0xC0000002'   # NTSTATUS
ERROR_CALL_NOT_IMPLEMENTED = '120'      # Win32 error (XAM's DWORD results)
SOCKET_ERROR = '-1'                     # Winsock / XNet results

# First matching prefix wins; anything else (allocators -> NULL, BOOLEAN -> FALSE,
# void functions, formatting -> 0 characters) returns 0.
FAILURES = [
    (('Nt', 'Io', 'Stfs', 'Xex', 'MicDeviceRequest', 'RmcDeviceRequest', 'XeKeysGetKey',
      'XeKeysConsoleSignatureVerification'), STATUS_NOT_IMPLEMENTED),
    (('NetDll_',), SOCKET_ERROR),
    (('Xam', 'XMsg'), ERROR_CALL_NOT_IMPLEMENTED),
]


def failure(name):
    for prefixes, value in FAILURES:
        if name.startswith(prefixes):
            return value
    return '0'


def main():
    names = sorted(set(re.findall(r'PPC_EXTERN_FUNC\(__imp__(\w+)\);', SHARED.read_text())))
    dao = set(re.findall(r'DAO_WEAK_STUB\((\w+)\)', DAO_STUBS.read_text()))
    new = [n for n in names if n not in dao]
    out = ['// Generated by sod360/scripts/gen_stubs_sod.py - do not edit.',
           '#include "stdafx.h"',
           '#include "function.h"',
           '',
           '#define SOD_WEAK_STUB(name) \\',
           '    __attribute__((weak)) PPC_FUNC(__imp__##name) { (void)base; ::sod::ReportStub(#name, ctx); ctx.r3.u64 = 0; }',
           '',
           '// Imports Dragon Age: Origins never used: unimplemented, a failure result by family',
           '// (NTSTATUS: STATUS_NOT_IMPLEMENTED; XAM: ERROR_CALL_NOT_IMPLEMENTED; NetDll: SOCKET_ERROR; else 0).',
           '#define SOD_UNIMPLEMENTED(name, result) \\',
           '    __attribute__((weak)) PPC_FUNC(__imp__##name) { (void)base; ::sod::ReportStub(#name, ctx); ctx.r3.s64 = int32_t(result); }',
           '']
    out += [f'SOD_WEAK_STUB({n})' for n in names if n in dao]
    out += ['']
    out += [f'SOD_UNIMPLEMENTED({n}, {failure(n)})' for n in new]
    OUT.write_text('\n'.join(out) + '\n')
    print(f'{len(names)} import stubs ({len(names) - len(new)} as DAO, {len(new)} new)')


if __name__ == '__main__':
    main()
